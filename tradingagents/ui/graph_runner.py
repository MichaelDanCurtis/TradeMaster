from __future__ import annotations

from collections.abc import Callable
from copy import deepcopy
from typing import Any

from tradingagents.default_config import DEFAULT_CONFIG
from tradingagents.ui.events import RunConfig, RunEvent
from tradingagents.ui.runner import RealRunResult


GraphFactory = Callable[..., Any]
ProviderConfigResolver = Callable[[], Any]
SecretStoreFactory = Callable[[str], Any]


ANALYST_NODE_NAMES = {
    "market": "Market Analyst",
    "social": "Social Analyst",
    "news": "News Analyst",
    "fundamentals": "Fundamentals Analyst",
}

REPORT_KEYS = {
    "market": "market_report",
    "social": "sentiment_report",
    "news": "news_report",
    "fundamentals": "fundamentals_report",
}

BASE_RECURSION_LIMIT = 250
RECURSION_LIMIT_PER_EXTRA_DEPTH = 80


class TradingAgentsGraphRunner:
    def __init__(
        self,
        *,
        graph_factory: GraphFactory | None = None,
        config_template: dict[str, Any] | None = None,
        provider_config_resolver: ProviderConfigResolver | None = None,
        secret_store_factory: SecretStoreFactory | None = None,
    ) -> None:
        self._graph_factory = graph_factory or self._default_graph_factory
        self._config_template = deepcopy(config_template or DEFAULT_CONFIG)
        self._provider_config_resolver = provider_config_resolver
        self._secret_store_factory = secret_store_factory

    def __call__(self, run_id: str, config: RunConfig) -> RealRunResult:
        graph_config = self._build_graph_config(config)
        graph = self._graph_factory(
            selected_analysts=config.analysts,
            debug=False,
            config=graph_config,
        )
        final_state, processed_signal = graph.propagate(config.ticker, config.trade_date)
        events = self._events_from_state(run_id, config, final_state, processed_signal)
        final_decision = str(final_state.get("final_trade_decision", processed_signal))
        rating = str(processed_signal)
        return RealRunResult(
            events=events,
            rating=rating,
            action=_action_from_rating(rating),
            thesis=final_decision,
            risk_notes="Generated by the real TradingAgents graph. Broker execution remains separately gated.",
        )

    def resolved_llm_metadata(self, config: RunConfig) -> dict[str, Any]:
        """Provider + models the graph will ACTUALLY run with.

        ``_build_graph_config`` overrides the inert RunConfig defaults
        (openai / gpt-5-mini / gpt-5) with the resolved research_llm provider
        config (e.g. github-copilot-oauth / gpt-4o-mini / gpt-4o). Trace
        metadata must record the resolved values so the trace surface tells
        the truth. Falls back to the RunConfig echo when resolution fails —
        the run itself will surface that failure.
        """
        try:
            graph_config = self._build_graph_config(config)
        except Exception:  # noqa: BLE001 — metadata must never block run creation
            return {
                "llm_provider": config.llm_provider,
                "quick_model": config.quick_model,
                "deep_model": config.deep_model,
            }
        return {
            "llm_provider": str(graph_config.get("llm_provider") or config.llm_provider),
            "quick_model": str(graph_config.get("quick_think_llm") or config.quick_model),
            "deep_model": str(graph_config.get("deep_think_llm") or config.deep_model),
        }

    def _build_graph_config(self, config: RunConfig) -> dict[str, Any]:
        graph_config = deepcopy(self._config_template)
        graph_config.update(
            {
                "llm_provider": config.llm_provider,
                "quick_think_llm": config.quick_model,
                "deep_think_llm": config.deep_model,
                "checkpoint_enabled": config.checkpoint,
                "max_debate_rounds": config.research_depth,
                "max_risk_discuss_rounds": config.research_depth,
                "max_recur_limit": max(
                    int(graph_config.get("max_recur_limit") or 0),
                    _recursion_limit_for_depth(config.research_depth),
                ),
            }
        )
        if self._provider_config_resolver is not None:
            self._apply_provider_config(graph_config, self._provider_config_resolver())
        return graph_config

    def _apply_provider_config(self, graph_config: dict[str, Any], provider_config: Any) -> None:
        config = dict(getattr(provider_config, "config", {}) or {})
        if config.get("runner_supported") is False or config.get("graph_runner_supported") is False:
            provider_id = getattr(provider_config, "provider_id", "selected provider")
            raise RuntimeError(f"{provider_id} does not have a graph runner adapter yet.")

        provider = _optional_string(config.get("provider"))
        if provider is not None:
            graph_config["llm_provider"] = provider

        base_url = _optional_string(config.get("base_url"))
        if base_url is not None:
            graph_config["backend_url"] = base_url

        model = _optional_string(config.get("model"))
        quick_model = _optional_string(config.get("quick_model")) or model
        deep_model = _optional_string(config.get("deep_model")) or model
        if quick_model is not None:
            graph_config["quick_think_llm"] = quick_model
        if deep_model is not None:
            graph_config["deep_think_llm"] = deep_model

        # Per-role model selection (PR 3): when the provider config
        # carries a ``role_models`` mapping, forward it to the graph
        # so TradingAgentsGraph builds per-role LLMs with the
        # operator's chosen models. Absence means "use the legacy
        # quick/deep split above".
        role_models = config.get("role_models")
        if isinstance(role_models, dict) and role_models:
            graph_config["role_models"] = role_models

        timeout = config.get("timeout")
        if timeout is not None:
            graph_config["timeout"] = float(timeout)

        recursion_limit = config.get("max_recur_limit", config.get("recursion_limit"))
        if recursion_limit is not None:
            graph_config["max_recur_limit"] = int(recursion_limit)

        if config.get("disable_structured_output") is not None:
            graph_config["disable_structured_output"] = bool(
                config.get("disable_structured_output")
            )

        configured_api_key = _optional_string(config.get("api_key"))
        if configured_api_key is not None:
            graph_config["api_key"] = configured_api_key
            return

        secret_ref = _optional_string(getattr(provider_config, "secret_ref", None))
        if secret_ref is not None and self._secret_store_factory is not None:
            graph_config["api_key"] = self._secret_store_factory(secret_ref).get_secret(secret_ref)
        elif config.get("auth_required") is False:
            graph_config["api_key"] = "local-no-auth"

    def _events_from_state(
        self,
        run_id: str,
        config: RunConfig,
        final_state: dict[str, Any],
        processed_signal: Any,
    ) -> list[RunEvent]:
        events: list[RunEvent] = []
        sequence = 1
        for analyst in config.analysts:
            node = ANALYST_NODE_NAMES[analyst]
            report_key = REPORT_KEYS[analyst]
            sequence = _append_report_events(
                events,
                run_id=run_id,
                sequence=sequence,
                node=node,
                section=analyst,
                report=final_state.get(report_key),
                message=f"Updated {analyst} report from real TradingAgents graph.",
                started_payload={"analyst": analyst, "source": "tradingagents-graph"},
            )

        investment_debate = _mapping(final_state.get("investment_debate_state"))
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Bull Researcher",
            section="bull_thesis",
            report=investment_debate.get("bull_history"),
            message="Updated bull researcher thesis from real TradingAgents graph.",
        )
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Bear Researcher",
            section="bear_thesis",
            report=investment_debate.get("bear_history"),
            message="Updated bear researcher thesis from real TradingAgents graph.",
        )
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Research Manager",
            section="research_manager",
            report=investment_debate.get("judge_decision") or final_state.get("investment_plan"),
            message="Updated research manager synthesis from real TradingAgents graph.",
        )
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Trader",
            section="trader_plan",
            report=final_state.get("trader_investment_plan"),
            message="Updated trader plan from real TradingAgents graph.",
        )

        risk_debate = _mapping(final_state.get("risk_debate_state"))
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Aggressive Analyst",
            section="aggressive_risk",
            report=risk_debate.get("current_aggressive_response"),
            message="Updated aggressive risk stance from real TradingAgents graph.",
        )
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Conservative Analyst",
            section="conservative_risk",
            report=risk_debate.get("current_conservative_response"),
            message="Updated conservative risk stance from real TradingAgents graph.",
        )
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Neutral Analyst",
            section="neutral_risk",
            report=risk_debate.get("current_neutral_response"),
            message="Updated neutral risk stance from real TradingAgents graph.",
        )
        sequence = _append_report_events(
            events,
            run_id=run_id,
            sequence=sequence,
            node="Portfolio Manager",
            section="portfolio_decision",
            report=final_state.get("final_trade_decision"),
            message="Updated portfolio manager decision from real TradingAgents graph.",
        )

        final_decision = str(final_state.get("final_trade_decision", processed_signal))
        rating = str(processed_signal)

        events.append(
            RunEvent(
                run_id=run_id,
                sequence=sequence,
                type="decision.created",
                node="Portfolio Manager",
                message="Created real TradingAgents decision.",
                payload={
                    "rating": rating,
                    "action": _action_from_rating(rating),
                    "final_trade_decision": final_decision,
                    "thesis": final_decision,
                    "risk_notes": "Generated by the real TradingAgents graph. Broker execution remains separately gated.",
                    "source": "tradingagents-graph",
                },
            )
        )
        return events

    @staticmethod
    def _default_graph_factory(**kwargs: Any) -> Any:
        from tradingagents.graph.trading_graph import TradingAgentsGraph

        return TradingAgentsGraph(**kwargs)


def _append_report_events(
    events: list[RunEvent],
    *,
    run_id: str,
    sequence: int,
    node: str,
    section: str,
    report: Any,
    message: str,
    started_payload: dict[str, Any] | None = None,
) -> int:
    report_text = str(report or "").strip()
    if not report_text:
        return sequence
    events.append(
        RunEvent(
            run_id=run_id,
            sequence=sequence,
            type="agent.started",
            node=node,
            message=f"{node} completed.",
            payload=started_payload or {"source": "tradingagents-graph"},
        )
    )
    sequence += 1
    events.append(
        RunEvent(
            run_id=run_id,
            sequence=sequence,
            type="report.updated",
            node=node,
            message=message,
            payload={
                "section": section,
                "report": report_text,
                "source": "tradingagents-graph",
            },
        )
    )
    return sequence + 1


def _mapping(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def _optional_string(value: Any) -> str | None:
    if value is None:
        return None
    text = str(value).strip()
    return text or None


def _recursion_limit_for_depth(research_depth: int) -> int:
    return BASE_RECURSION_LIMIT + max(0, research_depth - 1) * RECURSION_LIMIT_PER_EXTRA_DEPTH


def _action_from_rating(rating: str) -> str:
    normalized = rating.strip().lower()
    if normalized in {"buy", "overweight"}:
        return "Buy"
    if normalized in {"sell", "underweight"}:
        return "Sell"
    return "Hold"
